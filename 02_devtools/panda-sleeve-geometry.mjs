// Extract runtime geometry without changing the user's full-canvas SVG exports.
// Run from the repository root: node 02_devtools/panda-sleeve-geometry.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformPandaArmPath } from '../pwa/src/constants/pandaArmMorph.js';

const IDENTITY = [1, 0, 0, 1, 0, 0];
const multiply = ([a, b, c, d, e, f], [g, h, i, j, k, l]) =>
  [a * g + c * h, b * g + d * h, a * i + c * j, b * i + d * j, a * k + c * l + e, b * k + d * l + f];

function transform(value = '') {
  let result = IDENTITY;
  for (const match of value.matchAll(/(matrix|translate|scale|rotate)\s*\(([^)]*)\)/g)) {
    const values = match[2].trim().split(/[\s,]+/).map(Number);
    if (values.some(item => !Number.isFinite(item))) throw new Error('Invalid sleeve transform');
    let matrix;
    if (match[1] === 'matrix' && values.length === 6) matrix = values;
    if (match[1] === 'translate' && values.length <= 2) matrix = [1, 0, 0, 1, values[0], values[1] || 0];
    if (match[1] === 'scale' && values.length <= 2) matrix = [values[0], 0, 0, values[1] ?? values[0], 0, 0];
    if (match[1] === 'rotate' && [1, 3].includes(values.length)) {
      const radians = values[0] * Math.PI / 180, cosine = Math.cos(radians), sine = Math.sin(radians);
      const [, x = 0, y = 0] = values;
      matrix = [cosine, sine, -sine, cosine, x - cosine * x + sine * y, y - sine * x - cosine * y];
    }
    if (!matrix) throw new Error('Unsupported sleeve transform');
    result = multiply(result, matrix);
  }
  if (value.replace(/(matrix|translate|scale|rotate)\s*\([^)]*\)/g, '').trim()) throw new Error('Unsupported sleeve transform');
  return result;
}

export function extractPandaSleeveGeometry(source) {
  const stack = [{ name: null, matrix: IDENTITY, fill: '#000000' }], paths = [];
  for (const match of source.matchAll(/<([^>]+)>/g)) {
    const tag = match[1];
    if (tag.startsWith('?xml')) continue;
    if (tag.startsWith('/')) {
      if (stack.pop()?.name !== tag.slice(1).trim()) throw new Error('Unbalanced sleeve SVG');
      continue;
    }
    const name = tag.match(/^\S+/)?.[0];
    if (!['svg', 'g', 'path', 'rect'].includes(name)) throw new Error(`Unsupported sleeve SVG element: ${name}`);
    const attrs = Object.fromEntries([...tag.matchAll(/([\w:-]+)\s*=\s*["']([^"']*)["']/g)].map(([, key, value]) => [key, value]));
    if (Object.keys(attrs).some(key => !['id', 'xmlns', 'viewBox', 'x', 'y', 'width', 'height', 'd', 'fill', 'transform'].includes(key))) {
      throw new Error('Sleeve SVG needs a lossless importer for its paint or clipping attributes');
    }
    const parent = stack.at(-1), matrix = multiply(parent.matrix, transform(attrs.transform));
    const fill = attrs.fill ?? parent.fill;
    if (name === 'path' || name === 'rect') {
      let d = attrs.d;
      if (name === 'rect') {
        const [x, y, width, height] = [attrs.x || 0, attrs.y || 0, attrs.width, attrs.height].map(Number);
        if (![x, y, width, height].every(Number.isFinite) || width <= 0 || height <= 0) throw new Error('Invalid sleeve rectangle');
        d = `M${x} ${y}L${x + width} ${y}L${x + width} ${y + height}L${x} ${y + height}Z`;
      }
      if (!d || !/^#[\da-f]{3,8}$/i.test(fill)) throw new Error('Sleeve SVG needs an explicit solid-color path');
      paths.push({ d: matrix.every((value, index) => value === IDENTITY[index]) ? d.replace(/\s+/g, ' ').trim()
        : transformPandaArmPath(d, matrix), fill });
    }
    if (!tag.endsWith('/')) stack.push({ name, matrix, fill });
  }
  if (stack.length !== 1 || !paths.length) throw new Error('Incomplete sleeve SVG');
  return paths;
}

export function serializePandaSleeveGeometry(geometry) {
  return '// Generated by 02_devtools/panda-sleeve-geometry.mjs from the approved wardrobe SVGs.\n'
    + '// Do not redraw paths here; regenerate after importing the source parts.\n'
    + `export const PANDA_SLEEVE_GEOMETRY = ${JSON.stringify(geometry, null, 2)};\n`;
}

// The Python importer supplies not-yet-written SVG bytes here. Computing all
// generated bytes first lets its existing transaction commit or roll back both.
export function pandaSleeveGeometryFromSources(sources) {
  if (!sources || typeof sources !== 'object' || Array.isArray(sources) || !Object.keys(sources).length) {
    throw new Error('Missing sleeve sources');
  }
  return Object.fromEntries(Object.entries(sources).map(([id, sides]) => {
    if (!/^[a-z0-9][a-z0-9_-]*$/.test(id) || ['left', 'right'].some(side => typeof sides?.[side] !== 'string')) {
      throw new Error('Incomplete sleeve set');
    }
    return [id, Object.fromEntries(['left', 'right'].map(side => [side, extractPandaSleeveGeometry(sides[side])]))];
  }));
}

export async function writePandaSleeveGeometry(root) {
  const catalog = JSON.parse(await fs.readFile(path.join(root, '03_data/panda/wardrobe.json'), 'utf8'));
  const geometry = {};
  for (const { id } of catalog.sets) {
    geometry[id] = {};
    for (const side of ['left', 'right']) {
      geometry[id][side] = extractPandaSleeveGeometry(await fs.readFile(path.join(root, `pwa/public/panda/wardrobe/${id}-sleeve-${side}.svg`), 'utf8'));
    }
  }
  const output = path.join(root, 'pwa/src/constants/pandaSleeveGeometry.js');
  const contents = serializePandaSleeveGeometry(geometry);
  const previous = await fs.readFile(output, 'utf8').catch(error => { if (error.code === 'ENOENT') return null; throw error; });
  if (previous !== contents) await fs.writeFile(output, contents, 'utf8');
  return geometry;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length === 3 && process.argv[2] === '--stdin') {
    let input = '';
    for await (const chunk of process.stdin) input += chunk;
    process.stdout.write(serializePandaSleeveGeometry(pandaSleeveGeometryFromSources(JSON.parse(input))));
  } else if (process.argv.length === 2) {
    const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
    const geometry = await writePandaSleeveGeometry(root);
    console.log(`Extracted ${Object.keys(geometry).length} sleeve sets without changing their source SVGs.`);
  } else throw new Error('Usage: node 02_devtools/panda-sleeve-geometry.mjs [--stdin]');
}
